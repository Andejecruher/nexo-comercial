export async function seedNeighborhoods(prisma: PrismaClient): Promise<void> {
  let created = 0;

  for (const rawName of NEIGHBORHOOD_NAMES) {
    const name = normalizeNeighborhoodName(rawName.colonia);
    const matchKey = neighborhoodMatchKey(rawName.colonia);
    const zone = normalizeNeighborhoodName(rawName.zona);
    const postalCode = rawName.cp;
    const municipality = rawName.municipio;
    // Dedup by (matchKey, municipality) so the same neighborhood name can
    // coexist across different municipalities (e.g. "San Marcos" in
    // Cintalapa vs Jiquipilas). Without municipality in the lookup, the
    // seeder would overwrite the first entry with the last one that shares
    // the same normalized name.
    const existing = await prisma.neighborhood.findFirst({
      where: { matchKey, municipality },
      select: { id: true },
    });

    if (existing) {
      await prisma.neighborhood.update({
        where: { id: existing.id },
        data: {
          name,
          zone,
          matchKey,
          postalCode,
          municipality,
          state: 'Chiapas',
          stateCode: 'CHP',
        },
      });
      continue;
    }

    await prisma.neighborhood.create({
      data: { name, zone, matchKey, postalCode, municipality, state: 'Chiapas', stateCode: 'CHP' },
    });
    created += 1;
  }

  console.log(`✅ ${created} neighborhoods seeded (${NEIGHBORHOOD_NAMES.length} names in catalog)`);
}
